function replaceBytes(buf, search, replace) {
  const out = [];
  let i = 0;
  while (i < buf.length) {
    let match = false;
    if (i + search.length <= buf.length) {
      match = true;
      for (let j = 0; j < search.length; j++) {
        if (buf[i + j] !== search[j]) { match = false; break; }
      }
    }
    if (match) {
      for (const b of replace) out.push(b);
      i += search.length;
    } else {
      out.push(buf[i]);
      i++;
    }
  }
  return Buffer.from(out);
}

